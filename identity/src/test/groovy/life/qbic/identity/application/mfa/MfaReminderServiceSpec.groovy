package life.qbic.identity.application.mfa

import life.qbic.identity.application.communication.CommunicationException
import life.qbic.identity.application.communication.Content
import life.qbic.identity.application.communication.EmailService
import life.qbic.identity.application.communication.Recipient
import life.qbic.identity.application.communication.Subject
import life.qbic.identity.domain.model.EmailAddress
import life.qbic.identity.domain.model.EncryptedPassword
import life.qbic.identity.domain.model.FullName
import life.qbic.identity.domain.model.User
import life.qbic.identity.domain.model.UserId
import life.qbic.identity.domain.model.mfa.MfaGrace
import life.qbic.identity.domain.model.mfa.MfaPolicyMode
import life.qbic.identity.domain.model.mfa.ProtectedSecret
import life.qbic.identity.domain.model.mfa.SecondFactor
import life.qbic.identity.domain.repository.MfaGraceRepository
import life.qbic.identity.domain.repository.SecondFactorRepository
import life.qbic.identity.domain.repository.UserRepository
import spock.lang.Specification
import spock.lang.Unroll

import java.time.Duration
import java.time.Instant

/**
 * <b>The reminder pass.</b>
 *
 * <p>The mail itself is not interesting; the decisions around it are. A reminder that goes out to
 * somebody who already enrolled is the application not noticing, a reminder that repeats on every pass
 * is a support ticket, and one that is silently skipped because the mail server hiccuped is a user who
 * meets the deadline unprepared. Each of those is pinned below.</p>
 */
class MfaReminderServiceSpec extends Specification {

    static final Instant DEADLINE = Instant.parse("2026-11-24T09:00:00Z")
    static final Duration SOON = Duration.ofHours(24)
    static final Duration FINAL = Duration.ofHours(2)
    static final ProtectedSecret SECRET =
            ProtectedSecret.ofBase64(Base64.encoder.encodeToString(new byte[32]))

    FakeGraces graces = new FakeGraces()
    FakeFactors factors = new FakeFactors()
    /** An id no account has: the window of a user row that is gone. */
    static final String ORPHAN = "0d6f2a51-8b93-4e77-a1c5-3f9b2d807e64"

    FakeUsers users = new FakeUsers()

    /** The real account's id, generated by User.create — the service resolves it through UserId. */
    String account
    FakeMail mail = new FakeMail()

    private MfaReminderService service(MfaPolicyMode mode = MfaPolicyMode.REQUIRED) {
        new MfaReminderService(graces, factors, users, mail,
                new MfaPolicy(mode.name(), Duration.ofHours(48), ""), SOON, FINAL, "/settings/two-factor")
    }

    def setup() {
        account = users.register("ada@example.org")
    }

    // ---------------------------------------------------------------- who is reminded

    def "a window with a day left produces the first reminder and records it"() {
        given:
        graces.open(account, DEADLINE)

        when:
        def sent = service().sendDueReminders(DEADLINE.minus(Duration.ofHours(12)))

        then:
        sent == 1
        mail.sent.size() == 1
        mail.sent[0].recipient.address() == "ada@example.org"
        mail.sent[0].subject.content().contains("One day")
        graces.due[account] != null
        graces.finalSent.isEmpty()
    }

    def "the same window does not produce a second mail on the next pass"() {
        given:
        graces.open(account, DEADLINE)
        def at = DEADLINE.minus(Duration.ofHours(12))
        service().sendDueReminders(at)

        expect: "the stamp, not the clock, is what makes this idempotent"
        (0..5).every { service().sendDueReminders(at.plus(Duration.ofMinutes(it))) == 0 }
        mail.sent.size() == 1
    }

    def "a few hours before the deadline the final reminder goes out"() {
        given:
        graces.open(account, DEADLINE)
        service().sendDueReminders(DEADLINE.minus(Duration.ofHours(12)))

        when:
        def sent = service().sendDueReminders(DEADLINE.minus(Duration.ofMinutes(30)))

        then:
        sent == 1
        mail.sent.size() == 2
        mail.sent[1].subject.content().contains("A few hours")
        graces.finalSent[account] != null
    }

    def "an account that enrolled in the meantime is not reminded"() {
        given:
        graces.open(account, DEADLINE)
        factors.save(SecondFactor.enrolTotp(account, SECRET, "iPhone", DEADLINE))

        when:
        def sent = service().sendDueReminders(DEADLINE.minus(Duration.ofHours(12)))

        then: "the user did what the mail asks; a reminder now is the application not noticing"
        sent == 0
        mail.sent.isEmpty()
    }

    @Unroll
    def "nothing is sent under #mode"() {
        given:
        graces.open(account, DEADLINE)

        when:
        def sent = service(mode).sendDueReminders(DEADLINE.minus(Duration.ofHours(1)))

        then: "no deadline exists, so a mail about one would be false"
        sent == 0
        mail.sent.isEmpty()

        where:
        mode << [MfaPolicyMode.OFF]
    }

    def "an expired window is not reminded"() {
        given:
        graces.open(account, DEADLINE)
        // the fake returns windows whose deadline is still ahead, mirroring the query
        graces.expired << account

        when:
        def sent = service().sendDueReminders(DEADLINE.plus(Duration.ofHours(1)))

        then:
        sent == 0
        mail.sent.isEmpty()
    }

    def "a window whose account disappeared is skipped without stopping the pass"() {
        given: "one orphaned window and one real one"
        graces.open(ORPHAN, DEADLINE)
        graces.open(account, DEADLINE)

        when:
        def sent = service().sendDueReminders(DEADLINE.minus(Duration.ofHours(12)))

        then: "the orphan is logged, and the other account still hears about its deadline"
        sent == 1
        mail.sent.size() == 1
    }

    def "a failed send is retried on the next pass, because nothing was stamped"() {
        given:
        graces.open(account, DEADLINE)
        mail.failing = true

        when:
        def first = service().sendDueReminders(DEADLINE.minus(Duration.ofHours(12)))

        then:
        first == 0
        graces.due.isEmpty()

        when: "the mail server recovers"
        mail.failing = false
        def second = service().sendDueReminders(DEADLINE.minus(Duration.ofHours(12)))

        then:
        second == 1
        graces.due[account] != null
    }

    def "the mail names the deadline and the way to the settings page"() {
        given:
        graces.open(account, DEADLINE)

        when:
        service().sendDueReminders(DEADLINE.minus(Duration.ofHours(12)))

        then: "a reminder without a deadline or a link is a nag, not a reminder"
        def body = mail.sent[0].content.content()
        body.contains("/settings/two-factor")
        body.contains("recovery codes")
        !body.contains("undefined")
    }

    // ---------------------------------------------------------------- fakes

    static class FakeGraces implements MfaGraceRepository {
        final Map<String, MfaGrace> stored = [:]
        final Map<String, Instant> due = [:]
        final Map<String, Instant> finalSent = [:]
        final Set<String> expired = []

        void open(String userId, Instant deadline) {
            stored[userId] = MfaGrace.start(userId, deadline.minus(Duration.ofHours(48)),
                    Duration.ofHours(48))
        }

        @Override
        Optional<MfaGrace> findByUserId(String userId) {
            Optional.ofNullable(stored[userId])
        }

        @Override
        MfaGrace startIfAbsent(MfaGrace candidate) {
            stored[candidate.userId()] = candidate
            return candidate
        }

        @Override
        List<MfaGrace> findActiveWithOutstandingReminder(Instant now) {
            stored.values().findAll { it.userId() !in expired }
        }

        @Override
        void markDueReminderSent(String userId, Instant now) {
            due[userId] = now
            // The stamp must land on the entity, not only in this map: MfaReminder reads it back from
            // the window, and a fake that answered from a side map would let the spec pass while the
            // production path re-sent the same mail on every pass.
            set(userId, "reminderDueSentAt", now)
        }

        @Override
        void markFinalReminderSent(String userId, Instant now) {
            finalSent[userId] = now
            set(userId, "reminderFinalSentAt", now)
        }

        private void set(String userId, String field, Instant value) {
            def f = MfaGrace.getDeclaredField(field)
            f.setAccessible(true)
            f.set(stored[userId], value)
        }
    }

    static class FakeFactors implements SecondFactorRepository {
        final List<SecondFactor> stored = []

        @Override
        SecondFactor save(SecondFactor factor) {
            stored << factor
            return factor
        }

        @Override
        Optional<SecondFactor> findById(long id) {
            Optional.empty()
        }

        @Override
        List<SecondFactor> findAllByUserId(String userId) {
            stored.findAll { it.userId() == userId }
        }

        @Override
        List<SecondFactor> findActiveByUserId(String userId) {
            stored.findAll { it.userId() == userId && it.isActive() }
        }

        @Override
        boolean hasActiveFactor(String userId) {
            !findActiveByUserId(userId).isEmpty()
        }
    }

    static class FakeUsers extends UserRepository {
        final Map<String, User> byId = [:]

        FakeUsers() {
            super(null)
        }

        /** @return the generated id, so the spec can build a window for this very account */
        String register(String email) {
            def user = User.create(FullName.from("Ada Example"), EmailAddress.from(email),
                    "ada", EncryptedPassword.from("s3cret-Passw0rd".toCharArray()))
            byId[user.id().get()] = user
            return user.id().get()
        }

        @Override
        Optional<User> findById(UserId id) {
            Optional.ofNullable(byId[id.get()])
        }
    }

    static class FakeMail implements EmailService {
        final List<Map> sent = []
        boolean failing = false

        @Override
        void send(Subject subject, Recipient recipient, Content content)
                throws CommunicationException {
            if (failing) {
                throw new CommunicationException("smtp down")
            }
            sent << [subject: subject, recipient: recipient, content: content]
        }
    }
}
